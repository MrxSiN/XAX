"""U1.4 browser workload: an interactive XAX page (ADR-103, ADR-104).

Two ordinary XAX functions for ``wasm32-browser-v1``:

* ``_start`` reads ``n`` from the URL query, registers ``on_click`` with
  ``body_on_click``, and renders ``"<n> <fib(n)>"``;
* ``on_click`` reads ``n`` back from the body text, increments it, and
  renders ``"<n+1> <fib(n+1)>"``.

Each function zero-fills a 32-byte stack buffer (explicit stores; nothing is
initialized implicitly), copies its source text in, parses the leading
decimal digits (stopping at the first non-digit), computes ``fib(n)`` modulo
2**64 with a loop, formats both numbers with ``udiv``/``urem`` and checked
stores, and replaces the body's text.  The page is generated by
:func:`xax_web.emit_browser_page`; no JavaScript is written by hand.

Run ``python -m benchmarks.browser_fib`` from ``compiler/`` to regenerate
``browser_fib_evidence.json`` (requires Node.js with Playwright and Chromium).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from xax_compiler import IntCompare, Operation, bits_type, stack_owner_type, wasm32_browser_target
from xax_graph_builder import GraphBuilder, program_store
from xax_wasm import compile_wasm
from xax_web import WebApi, emit_browser_page, run_browser_page, web_api

EVIDENCE = Path(__file__).resolve().parent / "browser_fib_evidence.json"
BUFFER = 32
CLICKS = 2
B1, B32, B64 = bits_type(1), bits_type(32), bits_type(64)
CASES = ("30", "90", "", "7x9")


def leading_number(text: str) -> int:
    digits = ""
    for character in text[:BUFFER]:
        if not character.isdigit():
            break
        digits += character
    return int(digits or "0") & 0xFFFFFFFF


def render(n: int) -> str:
    a, b = 0, 1
    for _ in range(n):
        a, b = b, (a + b) & 0xFFFFFFFFFFFFFFFF
    return f"{n} {a}"


def expected_texts(query: str) -> list[str]:
    """Body text after loading, then after each click."""
    n = leading_number(query)
    return [render((n + clicks) & 0xFFFFFFFF) for clicks in range(CLICKS + 1)]


def _page_function(api: WebApi, owner_type, source, increment: int, registration=None):
    """``fn(page) -> page``: read ``source`` text, parse ``n``, add ``increment``, render ``"n fib(n)"``."""
    graph = GraphBuilder()
    tokens = (api.page_effect, api.memory_effect, owner_type)
    block = graph.block
    entry = block(api.page_effect)
    parse_test, parse_load, parse_step = block(B32, B32, *tokens), block(B32, B32, *tokens), block(B32, B32, B32, *tokens)
    fib_init, fib_test, fib_step = block(B32, *tokens), block(B32, B64, B64, *tokens), block(B32, B64, B64, *tokens)
    c32 = lambda at, value: at.const(B32, value)
    c64 = lambda at, value: at.const(B64, value)
    compare = lambda at, predicate, left, right: at.op1(Operation.INT_COMPARE, (left, right), B1, attributes=(predicate,))

    # Zero-fill the buffer, optionally register the click entry, copy the source text in.
    buffer, owner, memory = entry.op(Operation.STACK_ALLOC, (), (api.bytes_rw, owner_type, api.memory_effect), attributes=(BUFFER, 1))
    zero = entry.const(api.b8, 0)
    for offset in range(BUFFER):
        address = buffer if offset == 0 else entry.op1(Operation.ADDRESS_OFFSET, (buffer,), api.bytes_rw, attributes=(offset,))
        memory = entry.op1(Operation.STORE_BITS_LE, (address, zero, memory), api.memory_effect, attributes=(1, 1))
    page = entry.params[0]
    if registration is not None:
        handler = entry.op1(Operation.FUNCTION_ADDRESS, (), api.event_entry, entity=registration)
        page = entry.op1(Operation.CALL_FOREIGN, (handler, page), api.page_effect, entity=api.body_on_click)
    length, page, memory = entry.op(Operation.CALL_FOREIGN, (buffer, c32(entry, BUFFER), page, memory), (B32, api.page_effect, api.memory_effect), entity=source)
    entry.br(parse_test, c32(entry, 0), c32(entry, 0), page, memory, owner)

    # Parse: while i < length and i < BUFFER and buffer[i] is a digit: n = n * 10 + digit.
    i, n, *state = parse_test.params
    more = parse_test.op1(Operation.BIT_AND, (compare(parse_test, IntCompare.ULT, i, length), compare(parse_test, IntCompare.ULT, i, c32(parse_test, BUFFER))), B1)
    parse_test.cbr(more, parse_load, (i, n, *state), fib_init, (n, *state))
    i, n, page, memory, owner = parse_load.params
    byte, memory = parse_load.op(Operation.CHECKED_LOAD_BITS_LE, (buffer, i, memory), (api.b8, api.memory_effect), attributes=(1, 1))
    digit = parse_load.op1(Operation.SUB_WRAP, (parse_load.op1(Operation.INT_ZERO_EXTEND, (byte,), B32), c32(parse_load, ord("0"))), B32)
    parse_load.cbr(compare(parse_load, IntCompare.ULT, digit, c32(parse_load, 10)), parse_step, (i, n, digit, page, memory, owner), fib_init, (n, page, memory, owner))
    i, n, digit, *state = parse_step.params
    scaled = parse_step.op1(Operation.MUL_WRAP, (n, c32(parse_step, 10)), B32)
    parse_step.br(parse_test, parse_step.op1(Operation.ADD_WRAP, (i, c32(parse_step, 1)), B32), parse_step.op1(Operation.ADD_WRAP, (scaled, digit), B32), *state)

    # fib(n) modulo 2**64.
    parsed, *state = fib_init.params
    count_n = fib_init.op1(Operation.ADD_WRAP, (parsed, c32(fib_init, increment)), B32) if increment else parsed
    fib_init.br(fib_test, c32(fib_init, 0), c64(fib_init, 0), c64(fib_init, 1), *state)
    k, a, b, *state = fib_test.params
    after_fib = block(B64, *tokens)
    fib_test.cbr(compare(fib_test, IntCompare.ULT, k, count_n), fib_step, (k, a, b, *state), after_fib, (a, *state))
    k, a, b, *state = fib_step.params
    fib_step.br(fib_test, fib_step.op1(Operation.ADD_WRAP, (k, c32(fib_step, 1)), B32), b, fib_step.op1(Operation.ADD_WRAP, (a, b), B64), *state)

    def format_decimal(start_block, value, start):
        """Blocks writing ``value`` in decimal at ``start``; returns ``(final block, end position)``."""
        count, write_init, write, done = block(B64, B32, *tokens), block(B32, *tokens), block(B32, B64, *tokens), block(*tokens)
        state = start_block.params[-3:]
        start_block.br(count, value, c32(start_block, 0), *state)
        rest, digits, *state = count.params
        digits = count.op1(Operation.ADD_WRAP, (digits, c32(count, 1)), B32)
        rest = count.op1(Operation.UDIV, (rest, c64(count, 10)), B64)
        count.cbr(compare(count, IntCompare.NE, rest, c64(count, 0)), count, (rest, digits, *state), write_init, (digits, *state))
        total, *state = write_init.params
        end = write_init.op1(Operation.ADD_WRAP, (start, total), B32)
        write_init.br(write, end, value, *state)
        position, rest, page, memory, owner = write.params
        position = write.op1(Operation.SUB_WRAP, (position, c32(write, 1)), B32)
        character = write.op1(Operation.ADD_WRAP, (
            write.op1(Operation.INT_TRUNCATE, (write.op1(Operation.UREM, (rest, c64(write, 10)), B64),), api.b8),
            write.const(api.b8, ord("0")),
        ), api.b8)
        memory = write.op1(Operation.CHECKED_STORE_BITS_LE, (buffer, position, character, memory), api.memory_effect, attributes=(1, 1))
        rest = write.op1(Operation.UDIV, (rest, c64(write, 10)), B64)
        write.cbr(compare(write, IntCompare.NE, position, start), write, (position, rest, page, memory, owner), done, (page, memory, owner))
        return done, end

    # "<n> <fib(n)>": n at 0, a space, then fib(n).
    value = after_fib.params[0]
    first_done, n_end = format_decimal(after_fib, after_fib.op1(Operation.INT_ZERO_EXTEND, (count_n,), B64), c32(after_fib, 0))
    page, memory, owner = first_done.params
    memory = first_done.op1(Operation.CHECKED_STORE_BITS_LE, (buffer, n_end, first_done.const(api.b8, ord(" ")), memory), api.memory_effect, attributes=(1, 1))
    fib_start = first_done.op1(Operation.ADD_WRAP, (n_end, c32(first_done, 1)), B32)
    spaced = block(*tokens)
    first_done.br(spaced, page, memory, owner)
    render_block, text_end = format_decimal(spaced, value, fib_start)

    # Render and release the buffer.
    page, memory, owner = render_block.params
    readable = render_block.op1(Operation.POINTER_CAST, (buffer,), api.bytes_read)
    page, memory = render_block.op(Operation.CALL_FOREIGN, (readable, text_end, page, memory), (api.page_effect, api.memory_effect), entity=api.set_body_text)
    render_block.op(Operation.STACK_END, (owner, memory), ())
    render_block.ret(page)
    return graph, graph.function((api.page_effect,), (api.page_effect,))


def fib_page_program():
    api = web_api()
    owner_type = stack_owner_type()
    click_graph, on_click = _page_function(api, owner_type, api.body_text_copy, 1)
    start_graph, start = _page_function(api, owner_type, api.query_copy, 0, registration=on_click)
    target = wasm32_browser_target()
    objects = (*api.types, *api.symbols, owner_type, *click_graph.objects.values(), *start_graph.objects.values())
    return program_store(start, target, objects), start, target


def compile_page() -> tuple[bytes, bytes]:
    """``(module, page)``."""
    reader, function, target = fib_page_program()
    image = compile_wasm(reader, function.cid, target.cid)
    return image.module, emit_browser_page(image)


def evidence() -> dict:
    module, page = compile_page()
    runs = []
    version = None
    for query in CASES:
        observed = run_browser_page(page, query, clicks=CLICKS)
        version = observed["version"]
        expected = expected_texts(query)
        runs.append({"query": query, "expected": expected, "observed": observed["texts"], "page_errors": observed["errors"], "passed": observed["texts"] == expected and not observed["errors"]})
    return {
        "format": "xax-browser-fib-evidence-v2",
        "label": "EXECUTED",
        "decision": ["ADR-103", "ADR-104"],
        "host": {"browser": f"Chromium {version} (headless, Playwright)"},
        "clicks_per_run": CLICKS,
        "module_bytes": len(module),
        "module_sha256": hashlib.sha256(module).hexdigest(),
        "page_bytes": len(page),
        "page_sha256": hashlib.sha256(page).hexdigest(),
        "runs": runs,
    }


def main() -> int:
    result = evidence()
    EVIDENCE.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if all(run["passed"] for run in result["runs"]) else 1


if __name__ == "__main__":
    sys.exit(main())
